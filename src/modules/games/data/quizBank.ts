/** 成语题（出题形式：给释义，选成语）。 */
export interface IdiomItem {
  /** 成语本体（答案） */
  idiom: string;
  /** 释义（题干） */
  meaning: string;
}

/** 歇后语题（出题形式：给前半句，选后半句）。 */
export interface ProverbItem {
  /** 前半句（题干） */
  front: string;
  /** 后半句（答案） */
  back: string;
}

/** 脑筋急转弯（出题形式：题干 + 四选一）。 */
export interface TeaserItem {
  /** 题干 */
  q: string;
  /** 答案 */
  a: string;
}

